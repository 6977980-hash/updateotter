"""Writes the Indonesian translation files (WordPress 6.5+ .l10n.php format) from tools/i18n/id.py.

Usage: python3 tools/i18n/build.py   (run from anywhere; CI runs it and fails on a diff)
Every key must still exist in the PHP source of its text domain, so a reworded English string
fails the build instead of silently showing English on /id/ pages.
"""
import os
import re
import sys

sys.dont_write_bytecode = True

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import id as tr  # noqa: E402

TARGETS = {
    'rbx-data': (tr.RBX_DATA, 'modules/rbx-data', 'modules/rbx-data/languages/rbx-data-id_ID.l10n.php'),
    'rbx-tools': (tr.RBX_TOOLS, 'modules/rbx-tools', 'modules/rbx-tools/languages/rbx-tools-id_ID.l10n.php'),
    'updateotter': (tr.UPDATEOTTER, '.', 'languages/updateotter-id_ID.l10n.php'),
}
STR = re.compile(r"'((?:[^'\\]|\\.)*)'")


def sources(base):
    out = []
    for d, _, files in os.walk(os.path.join(ROOT, base)):
        rel = os.path.relpath(d, ROOT)
        if rel.startswith('.git') or (base == '.' and rel.startswith('modules')):
            continue
        out += [open(os.path.join(d, f), encoding='utf-8').read() for f in files if f.endswith('.php') and not f.endswith('.l10n.php')]
    return '\n'.join(out)


def php(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


errors = []
for domain, (strings, base, out) in TARGETS.items():
    src = sources(base)
    for k in strings:
        if php(k) not in src:
            errors.append(f'{domain}: not in source: {k!r}')
    lines = ['<?php', '// Generated by tools/i18n/build.py from tools/i18n/id.py. Do not edit.',
             "return array( 'domain' => " + php(domain) + ", 'language' => 'id_ID', 'plural-forms' => 'nplurals=1; plural=0;', 'messages' => array("]
    for k in sorted(strings):
        lines.append('\t' + php(k) + ' => ' + php(strings[k]) + ',')
    lines.append(') );')
    path = os.path.join(ROOT, out)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
if errors:
    print('\n'.join(errors))
    sys.exit(1)
print('ok')
